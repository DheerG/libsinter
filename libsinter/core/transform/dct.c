/* ── Generic N-point forward/inverse DCT (supports 4, 8, 16, 32) ── */
static const int16_t *dct_matrix(int size) {
    switch (size) {
        case  4: return &DCT4_MAT[0][0];
        case  8: return &DCT8_MAT[0][0];
        case 16: return &DCT16_MAT[0][0];
        case 32: return &DCT32_MAT[0][0];
        default: return NULL;
    }
}

void snt_dct_fwd_n_ref(const int16_t *in, int16_t *out, int size) {
    const int16_t *mat = dct_matrix(size);
    for (int k = 0; k < size; k++) {
        int32_t sum = 0;
        for (int n = 0; n < size; n++)
            sum += (int32_t)mat[k * size + n] * in[n];
        out[k] = (int16_t)snt_rshift_round_signed(sum, DCT_SHIFT);
    }
}

void snt_dct_inv_n_ref(const int16_t *in, int16_t *out, int size) {
    const int16_t *mat = dct_matrix(size);
    for (int n = 0; n < size; n++) {
        int32_t sum = 0;
        for (int k = 0; k < size; k++)
            sum += (int32_t)mat[k * size + n] * in[k];
        out[n] = (int16_t)snt_rshift_round_signed(sum, DCT_SHIFT);
    }
}

/* ── 2D Forward DCT (supports 4, 8, 16, 32) ──────────────────────── */
void snt_dct_fwd_2d_ref(const int16_t *block, int stride, int size,
                         int16_t *coeffs) {
    int16_t tmp[32 * 32]; /* max 32x32 */

    /* Row transforms */
    for (int y = 0; y < size; y++)
        snt_dct_fwd_n_ref(&block[y * stride], &tmp[y * size], size);

    /* Column transforms */
    int16_t col_in[32], col_out[32];
    for (int x = 0; x < size; x++) {
        for (int y = 0; y < size; y++)
            col_in[y] = tmp[y * size + x];
        snt_dct_fwd_n_ref(col_in, col_out, size);
        for (int y = 0; y < size; y++)
            coeffs[y * size + x] = col_out[y];
    }
}

/* ── 2D Inverse DCT (supports 4, 8, 16, 32) ──────────────────────── */
void snt_dct_inv_2d_ref(const int16_t *coeffs, int size,
                         int16_t *block, int stride) {
    int16_t tmp[32 * 32];

    /* Column inverse transforms */
    int16_t col_in[32], col_out[32];
    for (int x = 0; x < size; x++) {
        for (int y = 0; y < size; y++)
            col_in[y] = coeffs[y * size + x];
        snt_dct_inv_n_ref(col_in, col_out, size);
        for (int y = 0; y < size; y++)
            tmp[y * size + x] = col_out[y];
    }

    /* Row inverse transforms */
    for (int y = 0; y < size; y++)
        snt_dct_inv_n_ref(&tmp[y * size], &block[y * stride], size);
}
