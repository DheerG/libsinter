"""Turn collect_stats counts into libsinter/codec/model_tables.h.

usage: make_tables.py STATS.txt [STATS.txt ...] > libsinter/codec/model_tables.h

Each model's starting table is its symbols' relative frequency in the
training encodes, in Q15, for each model set (P, B) and QP class. A
(set, class, model) with fewer than MIN_COUNT symbols keeps the uniform
start. Every symbol keeps a probability of at least 1/32768.
"""
import sys
from collections import defaultdict

MIN_COUNT = 200
counts = defaultdict(lambda: [0] * 256)
nsets = nclasses = nmodels = 0
size_of = {}
for path in sys.argv[1:]:
    for line in open(path):
        f = list(map(int, line.split()))
        s, c, k, size_of[k], h = f[0], f[1], f[2], f[3], f[4:]
        acc = counts[(s, c, k)]
        for i, v in enumerate(h):
            acc[i] += v
        nsets, nclasses, nmodels = max(nsets, s + 1), max(nclasses, c + 1), max(nmodels, k + 1)

sizes = [size_of[k] for k in range(nmodels)]
offsets = [0]
for n in sizes:
    offsets.append(offsets[-1] + n)

out = sys.stdout
out.write("/*\n * Sinter Codec — Trained starting tables for the entropy models (normative)\n")
out.write(" *\n * Generated by tools/train/make_tables.py from tools/train/collect_stats\n")
out.write(" * runs on Xiph CIF clips that are not used for evaluation. Do not edit.\n")
import os
out.write(" * Training data: " + ", ".join(sorted(os.path.basename(p).rsplit(".", 1)[0] for p in sys.argv[1:])) + ".\n")
out.write(" * Q15 probabilities per model set (P, B), QP class and model, in the\n * struct order of SntCdfSet.\n */\n")
out.write("#ifndef SNT_MODEL_TABLES_H\n#define SNT_MODEL_TABLES_H\n\n#include <stdint.h>\n\n")
out.write(f"_Static_assert(sizeof(SntCdfSet) / sizeof(SntModel) == {nmodels}, \"regenerate model_tables.h\");\n\n")
out.write(f"static const uint16_t snt_trained_offset[{nmodels + 1}] = {{{', '.join(map(str, offsets))}}};\n\n")
valid = []
out.write(f"static const uint16_t snt_trained_prob[{nsets}][{nclasses}][{offsets[-1]}] = {{\n")
for s in range(nsets):
    out.write(" {\n")
    vrow = []
    for c in range(nclasses):
        vals, v = [], []
        for k in range(nmodels):
            h = counts[(s, c, k)][:sizes[k]]
            tot = sum(h)
            v.append(1 if tot >= MIN_COUNT else 0)
            if tot < MIN_COUNT:
                vals += [32768 // sizes[k]] * sizes[k]
            else:
                vals += [max(1, round(x * 32768 / tot)) for x in h]
        vrow.append(v)
        out.write("  {")
        for i in range(0, len(vals), 32):
            out.write(("" if i == 0 else "   ") + ",".join(map(str, vals[i:i + 32])) + ",\n")
        out.write("  },\n")
    valid.append(vrow)
    out.write(" },\n")
out.write("};\n\n")
out.write(f"static const uint8_t snt_trained_valid[{nsets}][{nclasses}][{nmodels}] = {{\n")
for s in range(nsets):
    out.write(" {\n")
    for c in range(nclasses):
        out.write("  {" + ",".join(map(str, valid[s][c])) + "},\n")
    out.write(" },\n")
out.write("};\n\n#endif /* SNT_MODEL_TABLES_H */\n")
